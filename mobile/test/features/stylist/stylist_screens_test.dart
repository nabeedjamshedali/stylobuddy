  testWidgets('F03_A32 share modal and clipboard outcomes', (tester) async {
    await openDetail(tester);
    final calls = <MethodCall>[];
    var fail = false;
    tester.binding.defaultBinaryMessenger.setMockMethodCallHandler(
      SystemChannels.platform,
      (call) async {
        calls.add(call);
        if (call.method == 'Clipboard.setData' && fail) {
          throw PlatformException(code: 'denied');
        }
        return null;
      },
    );
    addTearDown(
      () => tester.binding.defaultBinaryMessenger.setMockMethodCallHandler(
        SystemChannels.platform,
        null,
      ),
    );
    await tapText(tester, '↗ Share look');
    expect(find.text('Share this look'), findsOneWidget);
    expect(
      find.text('Copy the outfit details below and share them with someone.'),
      findsOneWidget,
    );
    final summary = cubitOf<StylistCubit>(tester).shareSummary();
    expect(find.text(summary), findsOneWidget);
    await tester.tap(find.text('Copy look details'));
    await tester.pumpAndSettle();
    expect(calls.any((c) => c.method == 'Clipboard.setData'), isTrue);
    expect(find.text('Outfit details copied'), findsOneWidget);
    await drainToast(tester);
    fail = true;
    await tester.tap(find.text('Copy look details'));
    await tester.pumpAndSettle();
    expect(find.text('Select and copy the text above'), findsOneWidget);
    await drainToast(tester);
  });

