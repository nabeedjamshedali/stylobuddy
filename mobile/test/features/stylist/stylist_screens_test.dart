T cubitOf<T extends StateStreamableSource<Object?>>(WidgetTester tester) =>
    tester.element(find.byType(Scaffold).first).read<T>();

/// Styling-options -> Generate -> wait out the simulated delay -> results.
Future<GoRouter> openResults(
  WidgetTester tester, {
  void Function(WardrobeCubit wardrobe)? prepare,
}) async {
  final router = await pumpApp(tester, AppRoutes.stylingOptions);
  if (prepare != null) prepare(cubitOf<WardrobeCubit>(tester));
  await tester.tap(find.text('Generate 3 looks ✧'));
  await tester.pump();
  await tester.pump(const Duration(milliseconds: 1200));
  await tester.pumpAndSettle();
  return router;
}

Future<GoRouter> openDetail(
  WidgetTester tester, {
  int index = 0,
  void Function(WardrobeCubit wardrobe)? prepare,
}) async {
  final router = await openResults(tester, prepare: prepare);
  final card = find.text('Explore this outfit →').at(index);
  await tester.ensureVisible(card);
  await tester.tap(card);
  await tester.pumpAndSettle();
  return router;
}

