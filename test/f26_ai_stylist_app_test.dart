/// Pumps the real [StyloBuddyApp]; [uid] null is a guest.
Future<GoRouter> _pump(
  WidgetTester tester, {
  String? uid = 'uid-1',
  FakeAiStylistClient? fake,
  RemoteConfigService? remoteConfig,
  String location = AppRoutes.stylist,
}) async {
  tester.view.physicalSize = const Size(390, 844);
  tester.view.devicePixelRatio = 1;
  addTearDown(tester.view.reset);
  final firestore = FakeFirebaseFirestore();
  if (uid != null) {
    for (final item in SeedData.items) {
      await firestore
          .collection('users/$uid/wardrobeItems')
          .doc(item.id)
          .set(FirestoreWardrobeRepository.seedFieldsFor(item));
    }
  }
  final router = createAppRouter(initialLocation: location);
  addTearDown(router.dispose);
  await tester.pumpWidget(
    StyloBuddyApp(
      router: router,
      uidStream: Stream<String?>.value(uid),
      initialUid: uid,
      firestoreOverride: firestore,
      remoteConfig: remoteConfig,
      aiStylistClient: fake,
    ),
  );
  await tester.pumpAndSettle();
  if (uid != null) {
    final deadline = DateTime.now().add(const Duration(seconds: 5));
    while (DateTime.now().isBefore(deadline)) {
      final count = _wardrobe(tester).state.items.length;
      if (count >= SeedData.items.length) break;
      await tester.runAsync(
        () => Future<void>.delayed(const Duration(milliseconds: 20)),
      );
      await tester.pump();
    }
    expect(_wardrobe(tester).state.items.length, SeedData.items.length);
  }
  return router;
}

T _read<T extends StateStreamableSource<Object?>>(WidgetTester tester) =>
    tester.element(find.byType(MaterialApp)).read<T>();

WardrobeCubit _wardrobe(WidgetTester tester) => _read<WardrobeCubit>(tester);
StylistCubit _stylist(WidgetTester tester) => _read<StylistCubit>(tester);

String _path(GoRouter router) =>
    router.routerDelegate.currentConfiguration.last.matchedLocation;

Future<void> _tap(WidgetTester tester, String text) async {
  await tester.ensureVisible(find.text(text));
  await tester.tap(find.text(text));
  await tester.pumpAndSettle();
}

/// Drives /styling-options -> 'Generate 3 looks ✧' -> /results.
Future<void> _generateViaUi(WidgetTester tester, GoRouter router) async {
  router.push(AppRoutes.stylingOptions);
  await tester.pumpAndSettle();
  await tester.tap(find.text('Generate 3 looks ✧'));
  await tester.pump();
  await tester.pump(const Duration(milliseconds: 1200));
  await tester.pumpAndSettle();
}

Finder _text(String s) => find.text(s, skipOffstage: false);

Future<void> _selectLockAndFind(WidgetTester tester, GoRouter router) async {
  router.push(AppRoutes.matchSelect);
  await tester.pumpAndSettle();
  await _tap(tester, 'White Oxford Shirt');
  await _tap(tester, 'Navy Chinos');
  router.push(AppRoutes.matchReview);
  await tester.pumpAndSettle();
  await _tap(tester, 'White Oxford Shirt');
  await _tap(tester, 'Continue to preferences →');
  await tester.tap(find.text('✧ Find my best matches'));
  await tester.pump();
  await tester.pump(const Duration(milliseconds: 1200));
  await tester.pumpAndSettle();
}

/// Texts that must never appear on the AI fallback path (F26-A68).
const _forbidden = [
  'ai styling failed',
  'limit',
  'unavailable',
  'error',
  'try again',
];

void _expectNoErrorUi(WidgetTester tester) {
  for (final w in tester.widgetList<Text>(find.byType(Text))) {
    final data = (w.data ?? w.textSpan?.toPlainText() ?? '').toLowerCase();
    for (final bad in _forbidden) {
      expect(data.contains(bad), isFalse, reason: '"$data" contains "$bad"');
    }
  }
  expect(find.byType(Dialog), findsNothing);
  expect(find.byType(SnackBar), findsNothing);
}

