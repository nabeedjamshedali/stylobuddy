/// Initialises with the defaults; the fetch lands when [fetched] completes.
class _GatedRemoteConfig implements RemoteConfigService {
  _GatedRemoteConfig(this.fetched);

  final Future<AppConfig?> fetched;

  @override
  Future<AppConfig> initialize() async => AppConfig.defaults;

  @override
  Future<AppConfig?> refresh() => fetched;
}
